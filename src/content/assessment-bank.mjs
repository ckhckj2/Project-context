// New process-learning cases grounded in the existing execution guides.
// No numeric legal thresholds or claims of professional certification.
// Each objective has two distinct situations for alternating retries.
function choice(id, trackId, level, taskId, objective, cases, options, explanation) {
  return {
    id,
    trackId,
    level,
    taskId,
    objective,
    cases,
    type: 'choice',
    options: options.map((value, index) => {
      const [label, feedback] = value.split('|');
      return { id: ['a', 'b', 'c', 'd', 'e'][index], label, feedback: feedback ?? explanation };
    }),
    answer: 'a',
    explanation,
    reviewStatus: 'process-reviewed',
  };
}
function order(id, trackId, level, taskId, objective, cases, steps, explanation) {
  return {
    id,
    trackId,
    level,
    taskId,
    objective,
    cases,
    type: 'order',
    options: steps.map((label, index) => ({ id: ['a', 'b', 'c'][index], label })),
    answer: ['a', 'b', 'c'],
    explanation,
    reviewStatus: 'process-reviewed',
  };
}
function short(id, trackId, level, taskId, objective, cases, aliases, explanation) {
  return {
    id,
    trackId,
    level,
    taskId,
    objective,
    cases,
    type: 'short',
    aliases,
    explanation,
    reviewStatus: 'process-reviewed',
  };
}
